// Generates src/core/casefold-data.ts from a downloaded Unicode CaseFolding.txt.
// Usage: bun run scripts/generate-case-folding.ts <CaseFolding.txt> <output.ts>
// It fetches nothing; the input file is data, parsed and never executed.

const SOURCE_URL_BASE = "https://www.unicode.org/Public";
const BACKSLASH = String.fromCharCode(92);

function fail(message: string): never {
	console.error(message);
	process.exit(1);
}

const [inputPath, outputPath] = process.argv.slice(2);
if (inputPath === undefined || outputPath === undefined) {
	fail(
		"usage: bun run scripts/generate-case-folding.ts <CaseFolding.txt> <output.ts>",
	);
}

const lines = (await Bun.file(inputPath).text()).split(/\r?\n/);
const versionMatch = /^# CaseFolding-(\d+\.\d+\.\d+)\.txt$/.exec(
	lines[0] ?? "",
);
const version = versionMatch?.[1];
if (version === undefined) {
	fail("the first line is not '# CaseFolding-<version>.txt'");
}

const entries = new Map<number, number[]>();
for (const line of lines) {
	const body = line.split("#")[0]?.trim() ?? "";
	if (body === "") continue;
	const [code, status, mapping] = body.split(";").map((part) => part.trim());
	if (code === undefined || status === undefined || mapping === undefined) {
		fail(`unreadable line: ${line}`);
	}
	if (status !== "C" && status !== "F") continue;
	const codePoint = Number.parseInt(code, 16);
	const mapped = mapping.split(/\s+/).map((part) => Number.parseInt(part, 16));
	if (Number.isNaN(codePoint) || mapped.some((value) => Number.isNaN(value))) {
		fail(`unreadable line: ${line}`);
	}
	if (entries.has(codePoint)) fail(`duplicate code point: ${code}`);
	entries.set(codePoint, mapped);
}

const escaped = (points: number[]): string =>
	points
		.map((point) => `${BACKSLASH}u{${point.toString(16).toUpperCase()}}`)
		.join("");

const rows = [...entries.entries()]
	.sort((a, b) => a[0] - b[0])
	.map(
		([codePoint, mapped]) =>
			`\t[0x${codePoint.toString(16).toUpperCase()}, "${escaped(mapped)}"],`,
	);

const output = `// Generated by scripts/generate-case-folding.ts from
// ${SOURCE_URL_BASE}/${version}/ucd/CaseFolding.txt
// (Unicode ${version}, statuses C and F only). Do not edit by hand: regenerate.

export const CASE_FOLDING_UNICODE_VERSION = "${version}";

export const CASE_FOLDING: ReadonlyMap<number, string> = new Map<number, string>([
${rows.join("\n")}
]);
`;

await Bun.write(outputPath, output);
console.log(`Unicode ${version}: ${entries.size} entries`);
